  function getLang() {
    if (current) return current;
    let saved = null;
    try { saved = localStorage.getItem(STORAGE_KEY); } catch (e) { /* нет доступа */ }
    current = saved === "be" ? "be" : "ru";
    return current;
  }

  function setLang(lang) {
    if (lang !== "ru" && lang !== "be") lang = "ru";
    current = lang;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* нет доступа */ }
    document.documentElement.lang = lang === "be" ? "be" : "ru";
    applyStatic();
    updateSwitcher();
    document.dispatchEvent(new CustomEvent("svaz:langchange", { detail: { lang: current } }));
  }

  function t(key) {
    const lang = getLang();
    let d = DICTIONARY[lang];
    if (d[key] === undefined && lang !== "ru") d = DICTIONARY.ru;
    return d[key] !== undefined ? d[key] : key;
  }

  /* выбрать строку из объекта { ru: ..., be: ... } */
  function tt(obj) {
    if (obj && typeof obj === "object" && !Array.isArray(obj)) {
      const lang = getLang();
      if (obj[lang] !== undefined) return obj[lang];
      if (obj.ru !== undefined) return obj.ru;
    }
    return obj;
  }

  function addParams(s, params) {
    return String(s).replace(/\{(\w+)\}/g, (m, k) => (params && params[k] !== undefined ? params[k] : m));
  }

  function tP(key, params) { return addParams(t(key), params); }

  function applyStatic() {
    document.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.getAttribute("data-i18n")); });
    document.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = t(el.getAttribute("data-i18n-html")); });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => { el.placeholder = t(el.getAttribute("data-i18n-placeholder")); });
    document.querySelectorAll("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria"))); });
    document.querySelectorAll("[data-i18n-alt]").forEach(el => { el.setAttribute("alt", t(el.getAttribute("data-i18n-alt"))); });
    const title = document.getElementById("page-title");
    if (title) title.textContent = t("meta.title");
    const desc = document.querySelector('meta[name="description"]');
    if (desc) desc.setAttribute("content", t("meta.description"));
  }

  function updateSwitcher() {
    document.querySelectorAll(".lang-switch__btn").forEach(b => {
      const on = b.getAttribute("data-lang") === getLang();
      b.classList.toggle("active", on);
      b.setAttribute("aria-pressed", String(on));
    });
  }

  function init() {
    document.querySelectorAll(".lang-switch__btn").forEach(b => {
      b.addEventListener("click", () => setLang(b.getAttribute("data-lang")));
    });
    setLang(getLang());
  }

  window.i18n = { getLang, setLang, t, tt, tP };

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
